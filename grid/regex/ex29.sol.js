const f = (text) => {
  const r = /\b(0[1-9]|1\d|2\d|3[0-1])\/(0[1-9]|1[0-2])\/\d{4}\b/g;
  return text.match(r) || [];
};

/**
 * Сложность: 7 = Знания 5 + Жирность 2
 * Знания 5 — альтернация-как-условие: 4 разноформенные ветки для дня
 *            (0[1-9]|1\d|2\d|3[0-1]) и ещё 2 для месяца — каждая ветка
 *            кодирует свою границу диапазона, а не просто выбор из вариантов
 * Жирность 2 — 51 символ, средняя длина
 */
module.exports = f;
