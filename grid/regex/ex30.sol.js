const f = (text) => {
  const r =
    /(?=\S*[A-Z]\S*)(?=\S*[a-z]\S*)(?=\S*[0-9]\S*)(?=\S*[!@#$%^&*]\S*)[A-Za-z0-9!@#$%^&*]{8,}/g;
  return text.match(r) || [];
};

/**
 * Сложность: 9 — 4 положительных lookahead-а подряд, каждый со своим условием
 *            (AND по 4 независимым проверкам в одной точке), без вложенности
 *            и без юникод-классов внутри — иначе была бы 10 (см. ex28)
 */
module.exports = f;
