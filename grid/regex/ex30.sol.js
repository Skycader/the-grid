const f = (text) => {
  const r =
    /(?=\S*[A-Z]\S*)(?=\S*[a-z]\S*)(?=\S*[0-9]\S*)(?=\S*[!@#$%^&*]\S*)[A-Za-z0-9!@#$%^&*]{8,}/g;
  return text.match(r) || [];
};

/**
 * Сложность: 9 = Знания 5 + Жирность 4
 * Знания 5 — 4 положительных lookahead-а подряд, каждый со своей ролью
 * Жирность 4 — 88 символов, вплотную к границе 90 (следующий порог)
 */
module.exports = f;
