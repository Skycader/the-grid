/**
 * Ex31
 * Найдите в тексте все валидные HEX-коды цветов.
 * Цвет может быть в формате #RGB, #RGBA, #RRGGBB или #RRGGBBAA.
 * Символы: 0-9, a-f, A-F.
 * Перед кодом не должно быть букв/цифр, после него — тоже.
 */

const f = (text) => {
  const r = /(#[A-Fa-f0-9]{3,4}\b)|(#[A-Fa-f0-9]{6}\b)|(#[A-Fa-f0-9]{8}\b)/gi;
  return text.match(r) || [];
};

/**
 * Сложность: 4 — три альтернативы (a|b|c), но все одной формы
 *            (#[A-Fa-f0-9]{N}\b, отличаются только N) — это плоская
 *            альтернация, не "альтернация-как-условие" (нет разных
 *            веток-правил, просто три варианта длины)
 */
module.exports = f;
