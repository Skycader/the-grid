/**
 * Ex31
 * Найдите в тексте все валидные HEX-коды цветов.
 * Цвет может быть в формате #RGB, #RGBA, #RRGGBB или #RRGGBBAA.
 * Символы: 0-9, a-f, A-F.
 * Перед кодом не должно быть букв/цифр, после него — тоже.
 * Сложность: ★★★★★★☆☆☆☆ (6/10)
 */

const f = (text) => {
  const r = /(#[A-Fa-f0-9]{3,4}\b)|(#[A-Fa-f0-9]{6}\b)|(#[A-Fa-f0-9]{8}\b)/gi;
  return text.match(r) || [];
};

/**
 * Сложность: 6 = Знания 3 + Жирность 3
 * Знания 3 — три альтернативы (a|b|c) из групп с якорем \b
 * Жирность 3 — 61 символ (три варианта длины кода сложены в один паттерн)
 * (config был 8 — расходился и с формулой, и с авторской пометкой выше; исправлено)
 */
module.exports = f;
